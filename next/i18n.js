const LANG_KEY = 'peaksurf_lang';
let _lang = (() => {
    try { const v = localStorage.getItem(LANG_KEY); if (v === 'fr' || v === 'en') return v; } catch (e) { /* ignore */ }
    return 'en';
})();
document.documentElement.lang = _lang;

function getLang() { return _lang; }
function getLocale() { return _lang === 'fr' ? 'fr-FR' : 'en-GB'; }
function setLang(lang) {
    if (lang !== 'fr' && lang !== 'en') return;
    _lang = lang;
    try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* ignore */ }
    document.documentElement.lang = lang;
}
/** Translate `key`, interpolating {name} placeholders. Falls back to French
    then to the key itself (visible in the UI, so misses get noticed). */
function t(key, params) {
    const dict = I18N[_lang] || I18N.fr;
    let s = dict[key];
    if (s == null) s = I18N.fr[key];
    if (s == null) return key;
    if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : ''));
    return s;
}
function applyI18n(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
    scope.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
    scope.querySelectorAll('[data-i18n-attr]').forEach(el => {
        el.getAttribute('data-i18n-attr').split(';').forEach(pair => {
            const i = pair.indexOf(':');
            if (i > 0) el.setAttribute(pair.slice(0, i).trim(), t(pair.slice(i + 1).trim()));
        });
    });
    if (scope === document) document.title = t('meta.title');
}
